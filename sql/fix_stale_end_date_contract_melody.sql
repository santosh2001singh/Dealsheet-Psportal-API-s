-- Melody Bonongwe (CANDIDATE_ID 25280540): placements 1454462 and 1467618 sit on the OLD contract
-- CHC18029 / H12951. They belong to CHC22056 / H15300 (run-rate 2026-06-24..2026-09-19).
--
-- Why: Nexus sent 1454462 (start 2026-06-22) with the previous assignment's TENTATIVE_END_DATE
-- 2026-05-16. That stale date fell inside CHC18029's run-rate window, so the row matched the old
-- contract and copied its SKU, initial start, AM and comments; 1467618 (start 2026-09-20) then
-- inherited the same contract from 1454462. The matcher now ignores end dates earlier than the
-- row's own start (buildLegacyContractLookupKey); this repairs the two rows already written.
--
-- Values come from the CHC22056 run-rate row. INITIAL_START_DATE = 2026-06-22 (the contract's first
-- segment starts before the run-rate row's 06-24). Manual columns take the run-rate value where it
-- has one. BACKOUT_OR_TERMINATION is cleared on 1467618 only (still running; 1454462 did end 09-19).
-- Every version of each placement is updated, so later update-appends carry the repaired values.


-- STEP 1 - preview: current vs new.
SELECT d.PLACEMENT_ID, d.LAST_UPDATED, d.PLACEMENT_STATUS,
       d.CONTRACT_ID, rr.CONTRACT_ID AS new_contract_id,
       d.SKU_NUMBER, rr.SKU_NUMBER AS new_sku,
       d.INITIAL_START_DATE, DATE '2026-06-22' AS new_initial_start_date,
       d.NEW_HIRE_DATE, rr.NEW_HIRE_DATE AS new_new_hire_date,
       d.ACCOUNT_MANAGER, rr.ACCOUNT_MANAGER AS new_account_manager,
       d.CREDENTIALING_SPECIALIST, rr.CREDENTIALING_SPECIALIST AS new_credentialing_specialist,
       d.BACKOUT_OR_TERMINATION
FROM `cynetdatabase.rr_project_data.cynet_health_deal_sheet` d
CROSS JOIN (
  SELECT * FROM `cynetdatabase.rr_project_data.all_CH_data_runrate`
  WHERE CONTRACT_ID = 'CHC22056' AND SKU_NUMBER = 'H15300'
) rr
WHERE CAST(d.PLACEMENT_ID AS STRING) IN ('1454462', '1467618')
ORDER BY d.PLACEMENT_ID, d.LAST_UPDATED;



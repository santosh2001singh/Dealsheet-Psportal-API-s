WITH l AS (
  SELECT *,
    CASE UPPER(TRIM(OWNERSHIP_ROLE))
      WHEN 'ONSITE AM' THEN 'ONSITE_AM'
      WHEN 'RECRUITER' THEN 'RECRUITER'
      WHEN 'ACCOUNT MANAGER' THEN 'ACCOUNT_MANAGER'
      WHEN 'ASSOCIATE AM' THEN 'ASSOCIATE_AM'
      WHEN 'SECONDARY AM' THEN 'SECONDARY_AM'
      WHEN 'TL' THEN 'TEAM_LEAD'
      WHEN 'TEAM LEAD' THEN 'TEAM_LEAD'
      WHEN 'VP / SR. VP' THEN 'VP'
      WHEN 'GROUP DIRECTOR / ASSOCIATE DIRECTOR' THEN 'ASSOCIATE_DELIVERY_DIRECTOR'
      WHEN 'GROUP DIRECTOR' THEN 'ASSOCIATE_DELIVERY_DIRECTOR'
      ELSE UPPER(TRIM(OWNERSHIP_ROLE)) END AS role_norm,
    -- Recruiter names carry a team tag, e.g. "Alan Rai (SPA)"; drop it so the person matches.
    LOWER(TRIM(REGEXP_REPLACE(IFNULL(PREVIOUS_OWNER_NAME, ''), r'\s*\([^)]*\)\s*$', ''))) AS prev_norm,
    LOWER(TRIM(REGEXP_REPLACE(IFNULL(NEW_OWNER_NAME, ''), r'\s*\([^)]*\)\s*$', '')))      AS new_norm,
    IF(CONTRACT_ID IS NULL, 'legacy', 'system') AS src
  FROM `cynetdatabase.rr_project_data.ownership_change_logs`
  WHERE IFNULL(IS_DELETED, FALSE) = FALSE AND SKU_NO IS NOT NULL
)
SELECT
  SKU_NO, ANY_VALUE(CONTRACT_ID) AS CONTRACT_ID, ANY_VALUE(CANDIDATE_NAME) AS candidate,
  role_norm AS role, ANY_VALUE(PREVIOUS_OWNER_NAME) AS previous_owner, ANY_VALUE(NEW_OWNER_NAME) AS new_owner,
  COUNT(*) AS log_rows,
  COUNT(DISTINCT IFNULL(PLACEMENT_ID, 'legacy')) AS placements,
  COUNT(DISTINCT OWNERSHIP_EFFECTIVE_DATE) AS distinct_eff_dates,
  STRING_AGG(DISTINCT CAST(OWNERSHIP_EFFECTIVE_DATE AS STRING) ORDER BY CAST(OWNERSHIP_EFFECTIVE_DATE AS STRING)) AS eff_dates,
  STRING_AGG(DISTINCT src) AS sources,
  STRING_AGG(CONCAT(IFNULL(PLACEMENT_ID, 'legacy'), ' -> ', IFNULL(CAST(OWNERSHIP_EFFECTIVE_DATE AS STRING), 'NULL'), ' [', ID, ']'), '  |  ' ORDER BY OWNERSHIP_EFFECTIVE_DATE) AS rows_detail
FROM l
GROUP BY SKU_NO, role_norm, prev_norm, new_norm
HAVING COUNT(*) > 1
ORDER BY distinct_eff_dates DESC, log_rows DESC
